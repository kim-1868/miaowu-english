import {test} from "node:test";
import assert from "node:assert/strict";
import {composeRainyNightSeasonDraft} from "../scripts/compose-rainy-night-s1-full.mjs";
import {buildRainyNightOccurrenceReview} from "../scripts/review-rainy-night-word-contexts.mjs";
import {buildRainyNightOfflineReviewDashboard} from "../scripts/build-rainy-night-review-dashboard.mjs";
import {evaluateRainyNightPublicationGate} from "../scripts/check-rainy-night-publishing-gate.mjs";
test("S62 private dashboard prioritizes real code-switch syntax hints without claiming approval",()=>{
 const {bundle}=composeRainyNightSeasonDraft();
 const rows=buildRainyNightOccurrenceReview(bundle).rows;
 const {html,summary}=buildRainyNightOfflineReviewDashboard(bundle);
 const expected=rows.filter(x=>x.reviewFlags.some(f=>f.startsWith("CODE_SWITCH_"))).length;
 const yes=(html.match(/data-syntax-risk="yes"/g)||[]).length;
 const no=(html.match(/data-syntax-risk="no"/g)||[]).length;
 assert.equal(yes,expected);
 assert.equal(yes+no,733);
 assert.match(html,/词性混排风险提示 · 非审核结论/);
 assert.ok(html.includes('<b>'+expected+'</b>词性混排风险提示'));
 assert.match(html,/id="syntaxRisk"/);
 assert.match(html,/syntaxRisk\.disabled=current!=="contexts"/);
 assert.match(html,/item\.dataset\.syntaxRisk===syntaxRisk\.value/);
 assert.match(html,/syntaxRisk\.addEventListener\("change",refresh\)/);
 assert.match(html,/存在误报；没有提示也不表示获得审核批准/);
 assert.equal(summary.reviewedWords,0);
 assert.equal(summary.reviewedContexts,0);
 assert.equal(summary.reviewedQuestions,0);
 assert.equal(summary.published,false);
 const gate=evaluateRainyNightPublicationGate(bundle);
 assert.equal(gate.status,"BLOCKED");
 assert.equal(gate.publicationAllowed,false);
 assert.equal(gate.productionDbTouched,false);
});
test("S62 offline HTML contains no added remote submission, server request or public book authorization",()=>{
 const {html}=buildRainyNightOfflineReviewDashboard(composeRainyNightSeasonDraft().bundle);
 assert.match(html,/connect-src &#39;none&#39;/);
 assert.ok(!html.includes("fetch("));
 assert.ok(!html.includes("<form"));
 assert.ok(!html.includes("https://api.cloudflare.com"));
 assert.ok(!html.includes('data-review-status="APPROVED"'));
});
